await db.exec(`select set_config('request.jwt.claim.sub', '${a}', false);`);
await assert.rejects(save(payload, [{...sets[0], exercise_id: otherExercise}]));
assert.equal((await db.query('select weight_lbs from workout_sets')).rows[0].weight_lbs, '160');
await db.exec('set role anon;');
