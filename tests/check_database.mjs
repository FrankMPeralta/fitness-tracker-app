import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_PATH);
const db = new PGlite();
const a = '11111111-1111-4111-8111-111111111111';
const b = '22222222-2222-4222-8222-222222222222';
const exercise = '33333333-3333-4333-8333-333333333333';
const otherExercise = '44444444-4444-4444-8444-444444444444';
const session = '55555555-5555-4555-8555-555555555555';
await db.exec(`
  create role authenticated; create role anon;
  create schema auth;
  create table auth.users(id uuid primary key);
  insert into auth.users values ('${a}'), ('${b}');
  create function auth.uid() returns uuid language sql stable as
    $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant usage on schema public, auth to authenticated, anon;
  grant execute on function auth.uid() to authenticated, anon;
  create table daily_entries(entry_date date, weight_lbs numeric);
  insert into daily_entries values ('2026-10-11', 190);
`);
const migration = await readFile(new URL('../migrations/001_workouts.sql', import.meta.url), 'utf8');
await db.exec(migration);
await db.exec(migration);
assert.equal((await db.query('select weight_lbs from daily_entries')).rows[0].weight_lbs, '190');
await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub', '${a}', false);`);
await db.query('insert into workout_exercises(id,user_id,name) values ($1,$2,$3)', [exercise, a, 'Squat']);
const prescription = [{exercise_id: exercise, name: 'Squat', set_count: 1, rep_min: 5, rep_max: 6}];
const payload = {id: session, performed_date: '2026-10-12', name: 'Lower A', prescription, status: 'completed', notes: 'Baseline'};
const sets = [{exercise_id: exercise, exercise_position: 0, set_number: 1, weight_lbs: 155, reps: 6, rir: 2, completed: true}];
const save = (s, entries) => db.query('select save_workout($1::jsonb,$2::jsonb)', [JSON.stringify(s), JSON.stringify(entries)]);
await save(payload, sets);
await save({...payload, notes: 'Updated'}, [{...sets[0], weight_lbs: 160}]);
assert.equal((await db.query('select count(*)::int as n from workout_sessions')).rows[0].n, 1);
assert.equal((await db.query('select weight_lbs from workout_sets')).rows[0].weight_lbs, '160');
